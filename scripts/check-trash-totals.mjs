import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
fs.mkdirSync('.sites-runtime',{recursive:true});
fs.writeFileSync('.sites-runtime/trash-finance.mjs',ts.transpileModule(fs.readFileSync('app/finance.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {businessBalance,monthly}=await import('../.sites-runtime/trash-finance.mjs');
const client={id:'sample',deleted_at:null,data:{status:'Contratado',serviceType:'Transporte',cypres:true,price:1000000,expenses:0,dispatchDate:'2026-10-08',vehicles:[{cost:3000000,weight:1,loadingRate:12000}]}};
const data={clients:[client],orders:[],payments:[{id:'payment',client_id:'sample',kind:'Cypres',amount:2000000,date:'2026-10-08'}],documents:[],ledger:[]};
assert.equal(businessBalance(data).profit,12000);
client.deleted_at='2026-10-08';
assert.deepEqual(businessBalance(data),{serviceProfit:0,expenses:0,withdrawals:0,profit:0,remaining:0,cash:0,cypresPending:0,advanced:0});
assert.equal(monthly(data,'2026-10').profit,12000);
client.deleted_at=null;
assert.equal(businessBalance(data).profit,12000);
data.clients=[];data.payments=[];
assert.equal(businessBalance(data).profit,0);
assert.equal(monthly(data,'2026-10').profit,0);
data.ledger=[{kind:'Gasto',amount:5000,date:'2026-10-08'},{kind:'Retiro',amount:2000,date:'2026-10-08'}];
assert.equal(businessBalance(data).profit,-5000);
assert.equal(businessBalance(data).remaining,-7000);
console.log('PASS: margen de $12.000, papelera sin utilidad ni cobros operativos, historial mensual, restauración, operación vacía y gastos reales.');
